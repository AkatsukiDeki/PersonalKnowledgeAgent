def generate_zip(output_path):
    with zipfile.ZipFile(output_path, 'w', zipfile.ZIP_DEFLATED) as zf:
        for folder, files in notes.items():
            for f in files:
                file_path = f"{folder}/{f['filename']}"
                zf.writestr(file_path, f['content'].encode('utf-8'))
    print(f"Test vault generated successfully at: {output_path}")

